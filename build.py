#!/usr/bin/env python3
"""
LA City pools — a working preview of the department's Citywide Aquatics page with one live
schedule behind every pool. Run `python3 build.py`; commit the HTML it writes.

  pools-base.json  every pool on the department's three lists: name, area, address, phone,
                   photo, map position (read from recreation.parks.lacity.gov on 2026-10-21)
  site.json        what this preview adds: Pool Relay view tokens, each pool's status note
                   when it has no schedule, and what we found on its page
"""

import html
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OFFICIAL = "https://recreation.parks.lacity.gov"
POOLS = json.load(open(os.path.join(HERE, "pools-base.json")))
SITE = json.load(open(os.path.join(HERE, "site.json")))
e = html.escape


def head(title, desc, depth=""):
    return f"""<!doctype html>
<!-- UNOFFICIAL PREVIEW. Not a City of Los Angeles website. Generated by build.py. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="robots" content="noindex, nofollow">
<title>{e(title)}</title>
<meta name="description" content="{e(desc)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Lato:wght@400;700;900&display=swap" rel="stylesheet">
<link rel="stylesheet" href="{depth}style.css">
</head>
<body>
"""


def chrome(official_url, what):
    return f"""<div class="preview-note"><b>Unofficial preview.</b> Not a City of Los Angeles page &mdash; a mock-up of
  <a href="{official_url}" target="_blank" rel="noopener noreferrer">{e(what)}</a> with every pool's hours on one live schedule.</div>
<div class="citybar"><span class="seal" aria-hidden="true"></span>An Official Website of the City of Los Angeles
  <span class="right"><span>City Services</span><span>City Directory</span></span></div>
<div class="deptband">City of Los Angeles Department of Recreation and Parks</div>
<header class="site">
  <div class="hdr-top"><span class="pill">English</span><span class="pill">Accessibility Menu</span>
    <span class="right"><span>No wrong DOOR</span><span>Virtual Recreation Resources</span></span></div>
  <div class="hdr-nav">
    <img class="logo" src="{OFFICIAL}/sites/default/files/logo_large.png" alt="LA Recreation and Parks">
    <span class="link">Home</span><span class="link">Activity Registration</span><span class="link">Facilities</span>
    <span class="link">Events</span><span class="link">Services</span><span class="link">About Us</span>
    <span class="search">Search</span><span class="login">Login</span>
  </div>
</header>
<div class="stripes"></div>
"""


def sidebar(depth, here):
    links = [
        ("Find a pool", f"{depth}index.html#find", "find"),
        ("Every pool, one day", f"{depth}index.html#day", "day"),
        ("Year-Round Pools", f"{depth}index.html#year-round", "yr"),
        ("Summer Pools", f"{depth}index.html#summer", "summer"),
        ("Camps With Pools", f"{depth}index.html#camps", "camps"),
        ("Fees and pool rules", f"{depth}index.html#fees", "fees"),
    ]
    official = [
        ("Aquatics Facility Use Permit", "/aquatic/facility-use-permit"),
        ("Learn to Swim Program", "/aquatic/learn-swim"),
        ("Job Training & Employment", "/aquatic/job-training"),
        ("Junior Lifeguard Training", "/aquatic/junior-lifeguard"),
        ("Lakes, Fishing & Beaches", "/aquatic/lakes-fishing-beaches"),
    ]
    li = "".join(f'<li class="{"here" if k == here else ""}"><a href="{h}">{e(t)}</a></li>' for t, h, k in links)
    lo = "".join(f'<li><a href="{OFFICIAL}{h}" target="_blank" rel="noopener">{e(t)}</a></li>' for t, h in official)
    return f"""<aside>
  <div class="card"><div class="card-header aq">Citywide Aquatics</div><ul>{li}</ul></div>
  <div class="card"><div class="card-header cat">On the department's site</div><ul>{lo}</ul></div>
</aside>"""


def footer(extra=""):
    return f"""<footer class="site"><div class="in">
  <strong>Citywide Aquatics</strong><br>3900 Chevy Chase Dr, Los Angeles, CA 90039 &middot; (323) 906-7953 &middot; Citywide.Aquatics@lacity.org{extra}
</div>
<p class="fine">This page is an unofficial preview built to demonstrate embedded
  <a href="https://www.poolrelay.com" target="_blank" rel="noopener noreferrer">Pool Relay</a> schedules. It is not operated by or
  affiliated with the City of Los Angeles or its Department of Recreation and Parks. Pool photos and facts are from
  <a href="{OFFICIAL}/aquatics" target="_blank" rel="noopener noreferrer">recreation.parks.lacity.gov</a>, read October 21, 2026.
  For official hours, fees and closures, see the department's site.</p>
</footer>"""


def pools_js():
    rows = []
    for p in POOLS:
        s = SITE["pools"].get(p["slug"], {})
        page = f"pools/{p['slug']}.html" if p["kind"] == "yearRound" else OFFICIAL + p["path"]
        rows.append(dict(
            slug=p["slug"], name=p["name"], area=p["area"], kind=p["kind"], address=p["address"],
            lat=p["lat"], lng=p["lng"], photo=(OFFICIAL + p["photo"]) if p.get("photo") else None,
            facility=s.get("facility"), closedNote=s.get("closedNote"), href=page,
        ))
    return "window.POOLS = " + json.dumps(rows, indent=0) + ";\n"


FEES = """<div class="fees">
  <table><tr><td>Infant (0&ndash;2)</td><td>Free</td></tr><tr><td>Children (3&ndash;17)</td><td>$1.00</td></tr>
    <tr><td>Adults (18&ndash;49)</td><td>$4.00</td></tr><tr><td>50 and up</td><td>$1.00</td></tr>
    <tr><td>Persons with disabilities</td><td>$1.00</td></tr><tr><td>Summer Youth Pass</td><td>$10</td></tr></table>
  <table><tr><td>Adult Lap Swim Pass, 30 entries</td><td>$88</td></tr>
    <tr><td>Youth, 50+ and persons with disabilities pass, 30 entries</td><td>$25</td></tr>
    <tr><td colspan="2" class="muted">Cash only at the pool. Passes are for year-round pools.</td></tr></table>
</div>"""


def index():
    yr = [p for p in POOLS if p["kind"] == "yearRound"]
    summer = [p for p in POOLS if p["kind"] == "summer"]
    camps = [p for p in POOLS if p["kind"] == "camp"]
    def item(p, href):
        return f'<li><a href="{href}">{e(p["name"])}</a><span>{e(p["area"])} &middot; {e(p["address"])}</span></li>'
    yr_list = "".join(item(p, f"pools/{p['slug']}.html") for p in sorted(yr, key=lambda p: p["name"]))
    su_list = "".join(f'<li><a href="{OFFICIAL}{p["path"]}" target="_blank" rel="noopener">{e(p["name"])}</a><span>{e(p["area"])} &middot; {e(p["address"])}</span></li>'
                      for p in sorted(summer, key=lambda p: p["name"]))
    ca_list = "".join(f'<li><a href="{OFFICIAL}{p["path"]}" target="_blank" rel="noopener">{e(p["name"])}</a><span>{e(p["address"])}</span></li>' for p in camps)
    v = SITE["views"]
    replaces = "".join(f"<li>{x}</li>" for x in SITE["replaces"])
    return head("LA City Pools", "Every City of Los Angeles pool on one live schedule: which are open right now, for what, and nearest to you.") + chrome(OFFICIAL + "/aquatics", "Citywide Aquatics & Swimming Pools") + f"""
<div class="wrap"><div class="cols">
{sidebar("", "find")}
<main class="sheet">
  <h1>Citywide Aquatics &amp; Swimming Pools</h1>
  <p class="lede">Where can you swim right now? Every City of Los Angeles pool, on one live schedule:
    which are open, for lap swim or rec swim, on how many lanes, until when, and which is nearest to you.</p>

  <div id="find"></div>
  <div id="finder" class="finder" data-view="{v['hub']}"></div>
  <p class="cal-foot">Live from each pool's published fall hours. Tap a pool for its full calendar, phone and
    directions. Lane counts marked as estimates are ours, until the pool tells us.</p>

  <h2 id="day">Every pool, one day</h2>
  <p style="margin:0 0 10px">One row per pool, morning to night. Page through the days, or tap a program below
    the calendar to see only that.</p>
  <div class="frame"><iframe src="https://www.poolrelay.com/embed/{v['day']}" height="{SITE['dayHeight']}" title="Every LA City pool, one day" loading="lazy"></iframe></div>
  <p class="cal-foot"><a href="https://www.poolrelay.com/v/{v['day']}" target="_blank" rel="noopener">Open it full screen</a>.</p>

  <div class="replaces">
    <h2>What this replaces</h2>
    <ul>{replaces}</ul>
  </div>

  <h2 id="year-round">Year-round pools <span class="muted" style="font-size:15px;font-weight:400">({len(yr)})</span></h2>
  <ul class="grid-list">{yr_list}</ul>

  <h2 id="summer">Summer pools <span class="muted" style="font-size:15px;font-weight:400">({len(summer)})</span></h2>
  <p style="margin:0 0 10px">Closed for the season. These outdoor pools open for afternoon public swim in summer;
    once their hours are entered they appear in the finder above like every other pool.</p>
  <ul class="grid-list">{su_list}</ul>

  <h2 id="camps">Camps with pools</h2>
  <ul class="grid-list">{ca_list}</ul>

  <h2 id="fees">Admission</h2>
  {FEES}
  <details class="more"><summary>Pool rules and swim attire</summary><div>
    <p>Children under 7 must be accompanied by an adult, one to one. Children under 4 need an approved swim diaper.
      Proper swim attire is required: no cut-offs, street shorts, white T-shirts or rash guards. You must take a swim
      test before entering the deep end. <a href="{OFFICIAL}/aquatics" target="_blank" rel="noopener">Full rules on the department's site</a>.</p>
    <p>All City aquatics facilities offer accessible ADA pool lifts; many offer universal changing rooms.</p>
  </div></details>
</main>
</div></div>
{footer()}
<script src="https://unpkg.com/leaflet@1.9.4/dist/leaflet.js" integrity="sha256-20nQCchB9co0qIjJZRGuk2/Z9VM+kNiyxNV1lvTlZBo=" crossorigin=""></script>
<link rel="stylesheet" href="https://unpkg.com/leaflet@1.9.4/dist/leaflet.css" integrity="sha256-p4NxAoJBhIIN+hmNHrzRCf9tD/miZyoHS5obTRR9BMY=" crossorigin="">
<script src="pools.js"></script>
<script src="finder.js"></script>
</body></html>
"""


def pool_page(p):
    s = SITE["pools"].get(p["slug"], {})
    official = OFFICIAL + p["path"]
    photo = f'<img src="{OFFICIAL}{p["photo"]}" alt="{e(p["name"])}">' if p.get("photo") else ""
    maps = "https://www.google.com/maps/search/?api=1&query=" + html.escape(p["address"].replace(" ", "+"))
    rows = [("Address", e(p["address"])), ("Area", e(p["area"]))]
    if p.get("phone"): rows.append(("Phone", e(p["phone"])))
    if p.get("email"): rows.append(("Email", e(p["email"])))
    if s.get("lanes"): rows.append(("The pool", e(s["lanes"])))
    if p.get("features"): rows.append(("Facility", e(p["features"])))
    if p.get("programs"): rows.append(("Programs", e(p["programs"])))
    facts = "".join(f"<dt>{k}</dt><dd>{v}</dd>" for k, v in rows)
    btns = f'<a class="btn" href="{maps}" target="_blank" rel="noopener">Get directions</a>'
    if p.get("brochure"):
        btns += f' <a class="btn ghost" href="{e(p["brochure"]["href"])}" target="_blank" rel="noopener">Fall brochure (PDF)</a>'
    btns += f' <a class="btn ghost" href="{official}" target="_blank" rel="noopener">The department\'s page</a>'
    if s.get("view"):
        cal = f"""<h2>Hours of operation</h2>
  <div id="today" class="today" data-view="{SITE['views']['hub']}" data-pool="{p['slug']}"><p class="muted" style="margin:0">Checking today&hellip;</p></div>
  <div class="frame"><iframe src="https://www.poolrelay.com/embed/{s['view']}" height="{s.get('height', 760)}" title="{e(p['name'])} schedule" loading="lazy"></iframe></div>
  <p class="cal-foot">{s.get('calNote', 'Tap a program under the calendar to see it on its own. Page ahead for holidays and closures.')}</p>"""
    else:
        cal = f"""<h2>Hours of operation</h2>
  <div class="today"><p class="state shut" style="margin:0;font-weight:700">{e(s.get('closedNote', 'Closed'))}</p></div>"""
    found = s.get("findings") or []
    finding = ""
    if found:
        finding = '<div class="finding"><b>What a swimmer runs into on the current page</b><ul>' + "".join(f"<li>{f}</li>" for f in found) + "</ul></div>"
    return head(f"{p['name']} — LA City Pools", f"{p['name']}: live hours, lanes and closures.", "../") + chrome(official, p["name"]) + f"""
<div class="wrap"><div class="cols">
{sidebar("../", "yr")}
<main class="sheet">
  <a class="back" href="../index.html">&lsaquo; All pools</a>
  <h1>{e(p['name'])}</h1>
  <div class="facts">{photo}<dl>{facts}</dl></div>
  <div class="btns">{btns}</div>
  {cal}
  {finding}
  <h2>Admission</h2>
  {FEES}
</main>
</div></div>
{footer()}
<script src="../pools.js"></script>
<script src="../finder.js"></script>
</body></html>
"""


def main():
    os.makedirs(os.path.join(HERE, "pools"), exist_ok=True)
    open(os.path.join(HERE, "pools.js"), "w").write(pools_js())
    open(os.path.join(HERE, "index.html"), "w").write(index())
    n = 0
    for p in POOLS:
        if p["kind"] == "yearRound":
            open(os.path.join(HERE, "pools", p["slug"] + ".html"), "w").write(pool_page(p))
            n += 1
    print(f"index.html + {n} pool pages")


if __name__ == "__main__":
    main()
